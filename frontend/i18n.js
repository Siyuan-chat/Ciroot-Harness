export const languages = { zh: '中文', en: 'English', ja: '日本語' };

export function resolveLocale(saved, browserLanguages=[]) {
  if (Object.hasOwn(languages, saved)) return saved;
  const requested=browserLanguages.map(value=>String(value||'').toLowerCase());
  if (requested.some(value=>value.startsWith('zh'))) return 'zh';
  if (requested.some(value=>value.startsWith('ja'))) return 'ja';
  return 'en';
}

