export function translate(value, language) {
  if (language === 'zh') return value;
  const translation = words[value];
  return translation?.[language === 'ja' ? 1 : 0] || value;
}

export function t(key, params={}, language='zh') {
  const template=messages[key]?.[language==='ja'?2:language==='en'?1:0]||key;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g,(_match,name)=>String(params[name]??''));
}

export function localize(root, language) {
  if (language === 'zh') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (['PRE', 'TEXTAREA', 'SCRIPT', 'STYLE', 'CODE', 'INPUT', 'OPTION'].includes(node.parentElement?.tagName) || node.parentElement?.closest('[data-source-content], [data-user-content], [data-report-content], [data-technical-content]')) continue;
    const value = node.nodeValue;
    const trimmed = value.trim();
    if (trimmed && words[trimmed]) node.nodeValue = value.replace(trimmed, translate(trimmed, language));
    else if (/^\d+ 个匹配 \/ 已载入 \d+ 项$/.test(trimmed)) {
      const [matches, loaded] = trimmed.match(/\d+/g);
      node.nodeValue = value.replace(trimmed, language === 'ja' ? `${matches} 件一致 / ${loaded} 件読み込み済み` : `${matches} matches / ${loaded} loaded`);
    }
    else if (trimmed.startsWith('覆盖 ')) node.nodeValue = value.replace('覆盖 ', language === 'ja' ? '対象範囲 ' : 'Coverage ');
  }
  for (const element of root.querySelectorAll('[placeholder], [title], [aria-label]')) {
    if (element.closest('[data-source-content], [data-user-content], [data-report-content], [data-technical-content]')) continue;
    for (const attribute of ['placeholder', 'title', 'aria-label']) {
      const value = element.getAttribute(attribute);
      if (value && words[value]) element.setAttribute(attribute, translate(value, language));
    }
  }
}
